//go:build ignore

// Command api_titles_gen writes api_titles.gen.go: the API's methods in the API's order, each
// with the first line of its documentation, read from the SDK's client. A Go program cannot
// read a method's documentation while it runs, and the SDK keeps it in its comments alone, so
// `pethost api` gets its list when the CLI is built. Run it with `go generate ./...` in cli/
// after the SDK changed; the CLI's workflow checks that the file is what it writes.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"unicode"
	"unicode/utf8"
)

func main() {
	found, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", "github.com/pethost-dev/sdk/go").Output()
	if err != nil {
		log.Fatalf("finding the SDK: %v", err)
	}
	dir := strings.TrimSpace(string(found))
	if dir == "" {
		log.Fatal("the SDK's source is not on this computer: run `go mod download` in cli/ first")
	}
	file, err := parser.ParseFile(token.NewFileSet(), filepath.Join(dir, "client.gen.go"), nil, parser.ParseComments)
	if err != nil {
		log.Fatal(err)
	}

	var out bytes.Buffer
	out.WriteString("// Code generated by api_titles_gen.go from the SDK's client. DO NOT EDIT.\n\npackage account\n\n")
	out.WriteString("// apiTitles are the API's methods in the API's order, each with the first line of its\n// documentation in the SDK.\n")
	out.WriteString("var apiTitles = []apiTitle{\n")
	for _, decl := range file.Decls {
		method, ok := decl.(*ast.FuncDecl)
		if !ok || method.Recv == nil || !method.Name.IsExported() || method.Doc == nil {
			continue
		}
		// "GetMachine: get the machine. It only reads."
		line, _, _ := strings.Cut(method.Doc.Text(), "\n")
		title := strings.TrimPrefix(line, method.Name.Name+": ")
		fmt.Fprintf(&out, "\t{%q, %q},\n", method.Name.Name, sentence(title))
	}
	out.WriteString("}\n")

	formatted, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("api_titles.gen.go", formatted, 0o644); err != nil {
		log.Fatal(err)
	}
}

// sentence is a title as a line of its own: its first letter a capital.
func sentence(title string) string {
	first, size := utf8.DecodeRuneInString(title)
	return string(unicode.ToUpper(first)) + title[size:]
}
